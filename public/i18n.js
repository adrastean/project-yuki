let activeLanguage = localStorage.getItem("yuki-ui-language") === "tr" ? "tr" : "en";

// Resolve a localized string and substitute named values. / Yerelleştirilmiş metni bulur ve değişkenleri yerleştirir.
export function t(key, values = {}) {
  const template = messages[activeLanguage]?.[key] ?? messages.en[key] ?? key;
  return template.replace(/\{\{(\w+)\}\}/g, (_match, name) => String(values[name] ?? ""));
}

export function getUiLanguage() {
  return activeLanguage;
}

// Update marked HTML copy and accessibility labels. / HTML metinlerini ve erişilebilirlik etiketlerini günceller.
export function applyTranslations(language = activeLanguage, root = document) {
  activeLanguage = language === "tr" ? "tr" : "en";
  document.documentElement.lang = activeLanguage;
  for (const node of root.querySelectorAll("[data-i18n]")) node.textContent = t(node.dataset.i18n);
  for (const node of root.querySelectorAll("[data-i18n-title]")) node.title = t(node.dataset.i18nTitle);
  for (const node of root.querySelectorAll("[data-i18n-aria]")) node.setAttribute("aria-label", t(node.dataset.i18nAria));
  for (const node of root.querySelectorAll("[data-i18n-placeholder]")) node.placeholder = t(node.dataset.i18nPlaceholder);
}

export function setUiLanguage(language) {
  activeLanguage = language === "tr" ? "tr" : "en";
  localStorage.setItem("yuki-ui-language", activeLanguage);
  applyTranslations(activeLanguage);
}
